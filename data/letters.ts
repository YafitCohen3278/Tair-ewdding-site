const FIRST_DAY_CAL =
  (process.env.FIRST_LETTER_OPENS_AT ?? "2026-05-17").trim().slice(0, 10);

function opensAtForLetter(id: number): string {
  const cal = addCalendarDaysUtc(FIRST_DAY_CAL, id - 1);
  const hour = id === 1 ? 6 : 0;
  return jerusalemWallClock(cal, hour, 0, 0).toISOString();
}

